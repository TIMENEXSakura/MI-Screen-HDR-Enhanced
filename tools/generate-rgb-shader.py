"""Keep the audited SkSL and native embedded bytes identical (no system SO)."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sources = {'hdr_rgb_original': root/'experiments/hdr-rgb/original_gainmap.sksl',
           'hdr_rgb_shader': root/'native/shaders/rgb_gainmap.sksl'}
text = '/* Generated by tools/generate-rgb-shader.py; do not edit. */\n'
for name, path in sources.items():
    text += 'static const unsigned char '+name+'[]=\n'
    text += '\n'.join(json.dumps(line) for line in path.read_text().splitlines(keepends=True))+';\n'
target = root/'native/rgb_shader_bytes.h'
if '--check' in sys.argv:
    assert target.read_text() == text, 'Regenerate native/rgb_shader_bytes.h'
else:
    target.write_text(text)
